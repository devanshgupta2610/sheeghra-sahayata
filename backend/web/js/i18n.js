function t(key) {
  const lang = localStorage.getItem("ss_user_lang") || "en";
  return (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key;
}

function toggleLang() {
  const cur = localStorage.getItem("ss_user_lang") || "en";
  localStorage.setItem("ss_user_lang", cur === "hi" ? "en" : "hi");
  location.reload();
}
